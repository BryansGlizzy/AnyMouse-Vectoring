/*
 * Host-side tests for the HID report-descriptor parser (components/amv_hid_parse).
 *
 *   cc -std=c11 -Wall -Wextra -Icomponents/amv_hid_parse/include tests/test_hid_parse.c \
 *      components/amv_hid_parse/amv_hid_parse.c -o /tmp/test_hid_parse && /tmp/test_hid_parse
 *
 * The descriptors here are hand-built to the shapes real mice use. Descriptors captured from
 * real hardware (the dongle can dump them) belong in tests/descriptors/ and get added below.
 */
#include <stdio.h>
#include <string.h>
#include "amv_hid_parse.h"

static int fails;
#define CHECK(c, ...) do { if (c) printf("  ok   " __VA_ARGS__); else { printf("  FAIL " __VA_ARGS__); fails++; } printf("\n"); } while (0)

/* HID 1.11 appendix B.2: boot-protocol mouse, 3 buttons, 8-bit X/Y, no report IDs */
static const uint8_t boot_mouse[] = {
    0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x09, 0x01, 0xA1, 0x00, 0x05, 0x09, 0x19, 0x01, 0x29, 0x03,
    0x15, 0x00, 0x25, 0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02, 0x95, 0x01, 0x75, 0x05, 0x81, 0x01,
    0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x02, 0x81, 0x06,
    0xC0, 0xC0 };

/* Gaming mouse shape: report ID 1, 16 buttons, 16-bit X/Y, 8-bit wheel, AC Pan; plus a vendor
 * collection with report ID 2 that must be ignored */
static const uint8_t gaming_mouse[] = {
    0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, 0x01, 0x09, 0x01, 0xA1, 0x00,
    0x05, 0x09, 0x19, 0x01, 0x29, 0x10, 0x15, 0x00, 0x25, 0x01, 0x95, 0x10, 0x75, 0x01, 0x81, 0x02,
    0x05, 0x01, 0x16, 0x01, 0x80, 0x26, 0xFF, 0x7F, 0x75, 0x10, 0x95, 0x02, 0x09, 0x30, 0x09, 0x31, 0x81, 0x06,
    0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x01, 0x09, 0x38, 0x81, 0x06,
    0x05, 0x0C, 0x0A, 0x38, 0x02, 0x95, 0x01, 0x81, 0x06,
    0xC0, 0xC0,
    0x06, 0x00, 0xFF, 0x09, 0x01, 0xA1, 0x01, 0x85, 0x02, 0x09, 0x02, 0x15, 0x00, 0x26, 0xFF, 0x00,
    0x75, 0x08, 0x95, 0x08, 0x81, 0x02, 0xC0 };

/* 12-bit packed X/Y (Logitech-style): 8 buttons, 12-bit signed X and Y */
static const uint8_t packed12[] = {
    0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x09, 0x01, 0xA1, 0x00, 0x05, 0x09, 0x19, 0x01, 0x29, 0x08,
    0x15, 0x00, 0x25, 0x01, 0x95, 0x08, 0x75, 0x01, 0x81, 0x02,
    0x05, 0x01, 0x16, 0x01, 0xF8, 0x26, 0xFF, 0x07, 0x75, 0x0C, 0x95, 0x02, 0x09, 0x30, 0x09, 0x31, 0x81, 0x06,
    0xC0, 0xC0 };

/* Keyboard + mouse in one descriptor (combo / macro pad): keyboard flagged, mouse still parsed */
static const uint8_t combo[] = {
    0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, 0x01, 0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00,
    0x25, 0x01, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02, 0xC0,
    0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, 0x02, 0x09, 0x01, 0xA1, 0x00, 0x05, 0x09, 0x19, 0x01, 0x29, 0x03,
    0x15, 0x00, 0x25, 0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02, 0x95, 0x01, 0x75, 0x05, 0x81, 0x01,
    0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x02, 0x81, 0x06, 0xC0, 0xC0 };

/* Absolute pointer (tablet): must not count as a vectorable mouse */
static const uint8_t tablet[] = {
    0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x09, 0x01, 0xA1, 0x00, 0x05, 0x09, 0x19, 0x01, 0x29, 0x01,
    0x15, 0x00, 0x25, 0x01, 0x95, 0x01, 0x75, 0x01, 0x81, 0x02, 0x95, 0x01, 0x75, 0x07, 0x81, 0x01,
    0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x15, 0x00, 0x26, 0xFF, 0x7F, 0x75, 0x10, 0x95, 0x02, 0x81, 0x02, 0xC0, 0xC0 };

/* Same as boot_mouse but the layout is set up with Push/Pop around the sizes */
static const uint8_t pushpop[] = {
    0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x09, 0x01, 0xA1, 0x00, 0xA4, 0x05, 0x09, 0x19, 0x01, 0x29, 0x03,
    0x15, 0x00, 0x25, 0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02, 0x95, 0x01, 0x75, 0x05, 0x81, 0x01, 0xB4,
    0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x02, 0x81, 0x06, 0xC0, 0xC0 };

int main(void)
{
    amv_hid_layout_t l;
    amv_hid_report_t r;

    printf("boot-protocol mouse\n");
    CHECK(amv_hid_parse(boot_mouse, sizeof boot_mouse, &l) == 0 && l.valid, "parses and is a vectorable mouse");
    CHECK(!l.uses_report_ids && l.num_buttons == 3, "no report IDs, 3 buttons");
    CHECK(l.x.bit_off == 8 && l.y.bit_off == 16 && l.x.bit_size == 8 && l.x.is_signed, "X at bit 8, Y at bit 16, 8-bit signed");
    CHECK(!l.wheel.present && !l.pan.present, "no wheel or pan");
    const uint8_t b1[] = { 0x05, 0xFB, 0x07 };       /* left+right..., dx=-5, dy=7 */
    CHECK(amv_hid_decode(&l, b1, sizeof b1, &r) && r.dx == -5 && r.dy == 7 && r.buttons == 5, "decodes dx=-5 dy=7 buttons=0b101");
    CHECK(!amv_hid_decode(&l, b1, 2, &r), "truncated report rejected");

    printf("gaming mouse: report ID, 16 buttons, 16-bit X/Y, wheel, pan, vendor collection\n");
    CHECK(amv_hid_parse(gaming_mouse, sizeof gaming_mouse, &l) == 0 && l.valid && l.uses_report_ids, "parses, uses report IDs");
    CHECK(l.num_buttons == 16 && l.x.bit_off == 16 && l.x.bit_size == 16 && l.y.bit_off == 32, "16 buttons, X at 16, Y at 32 (16-bit)");
    CHECK(l.wheel.bit_off == 48 && l.pan.bit_off == 56 && l.wheel.report_id == 1, "wheel at 48, pan at 56, report 1");
    const uint8_t g1[] = { 0x01, 0x03, 0x80, 0x34, 0x12, 0x00, 0xFE, 0x01, 0xFF };   /* btn1+2+16, dx=0x1234, dy=-512, wheel=1, pan=-1 */
    CHECK(amv_hid_decode(&l, g1, sizeof g1, &r) && r.dx == 0x1234 && r.dy == -512 && r.wheel == 1 && r.pan == -1, "decodes 16-bit deltas, wheel and pan");
    CHECK(r.buttons == (0x8003u) && (r.have & AMV_HID_HAVE_BUTTONS), "buttons 1, 2 and 16");
    const uint8_t g2[] = { 0x02, 1, 2, 3, 4, 5, 6, 7, 8 };
    CHECK(!amv_hid_decode(&l, g2, sizeof g2, &r), "vendor report ID 2 is not mouse data");

    printf("12-bit packed X/Y\n");
    CHECK(amv_hid_parse(packed12, sizeof packed12, &l) == 0 && l.valid && l.x.bit_size == 12 && l.y.bit_off == 20, "12-bit X at 8, Y at 20");
    const uint8_t p1[] = { 0x01, 0xF0, 0x7F, 0x00 };  /* dx = 0x0F0 | ((0x7F&0xF)<<8)... computed below */
    /* bytes: [btn][x7:0][y3:0 x11:8][y11:4] -> x = 0xF0 | (0xF<<8) = 0xFF0 = -16; y = 0x7 | (0x00<<4)... */
    amv_hid_decode(&l, p1, sizeof p1, &r);
    CHECK(r.dx == -16 && r.dy == 7 && r.buttons == 1, "sign-extends 12-bit values across a byte boundary (dx=-16, dy=7)");

    printf("keyboard + mouse combined\n");
    CHECK(amv_hid_parse(combo, sizeof combo, &l) == 0 && l.valid && l.has_keyboard && l.uses_report_ids, "mouse found, keyboard flagged");
    const uint8_t c1[] = { 0x02, 0x01, 0x04, 0xFC };
    CHECK(amv_hid_decode(&l, c1, sizeof c1, &r) && r.dx == 4 && r.dy == -4 && r.buttons == 1, "mouse report decoded");
    const uint8_t c2[] = { 0x01, 0x02 };
    CHECK(!amv_hid_decode(&l, c2, sizeof c2, &r), "keyboard report ignored");

    printf("absolute pointer\n");
    CHECK(amv_hid_parse(tablet, sizeof tablet, &l) == 0 && !l.valid && l.absolute && l.has_mouse, "flagged absolute, not vectorable");

    printf("push / pop\n");
    CHECK(amv_hid_parse(pushpop, sizeof pushpop, &l) == 0 && l.valid && l.num_buttons == 3 && l.x.bit_off == 8, "same layout as the plain boot mouse");

    printf("malformed input\n");
    const uint8_t trunc[] = { 0x05, 0x01, 0x09, 0x02, 0xA1 };
    CHECK(amv_hid_parse(trunc, sizeof trunc, &l) < 0 || !l.valid, "unterminated collection is not valid");
    const uint8_t cut[] = { 0x05, 0x01, 0x09 };
    CHECK(amv_hid_parse(cut, sizeof cut, &l) < 0, "item cut short rejected");
    const uint8_t pop[] = { 0xB4 };
    CHECK(amv_hid_parse(pop, sizeof pop, &l) < 0, "Pop with empty stack rejected");
    CHECK(amv_hid_parse(NULL, 0, &l) == 0 && !l.valid, "empty descriptor: nothing valid");

    printf(fails ? "\n%d FAILED\n" : "\nAll checks passed\n", fails);
    return fails != 0;
}
